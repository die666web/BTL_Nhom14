#!/usr/bin/env python3
"""Source manifests -> Make include + Keil ARM Compiler 6 projects (app + bootloader).
   tools/sources.json            -> APP_SRCS,  keil/MCU_Project.uvprojx (0x08002000, 55 KiB)
   tools/bootloader_sources.json -> BOOT_SRCS, keil/Bootloader.uvprojx  (0x08000000, 8 KiB)
   Layout phải khớp common/ota_frame/ota_layout.h."""
import argparse
import json
from pathlib import Path
import xml.etree.ElementTree as ET
root = Path(__file__).resolve().parents[1]

def load(name):
    groups = json.loads((root / name).read_text())
    sources = [path for items in groups.values() for path in items]
    if len(sources) != len(set(sources)):
        raise SystemExit('Duplicate sources in ' + name)
    for path in sources:
        if not (root / path).is_file(): raise SystemExit('Missing: ' + path)
    return groups, sources

app_groups, app_sources = load('tools/sources.json')
boot_groups, boot_sources = load('tools/bootloader_sources.json')

def mk_list(var, sources):
    return var + ' := ' + ' \\\n    '.join(sources) + '\n'
mk = ('# Generated by tools/sync_projects.py; edit tools/sources.json / tools/bootloader_sources.json.\n'
      + mk_list('APP_SRCS', app_sources) + mk_list('BOOT_SRCS', boot_sources))

def sub(parent, tag, value=None):
    node=ET.SubElement(parent,tag)
    if value is not None: node.text=str(value)
    return node

def project(target_name, groups, irom_base, irom_size, scatter, output_name, includes, optim):
    project = ET.Element('Project', {'xmlns:xsi':'http://www.w3.org/2001/XMLSchema-instance','xsi:noNamespaceSchemaLocation':'project_projx.xsd'})
    sub(project,'SchemaVersion','2.1')
    sub(project,'Header','### uVision Project, (C) Keil Software')
    target=sub(sub(project,'Targets'),'Target')
    for k,v in [('TargetName',target_name),('ToolsetNumber','0x4'),('ToolsetName','ARM-ADS'),('uAC6','1')]:sub(target,k,v)
    opt=sub(target,'TargetOption'); common=sub(opt,'TargetCommonOption')
    for k,v in [('Device','STM32F103C8'),('Vendor','STMicroelectronics'),
     ('Cpu','IRAM(0x20000000,0x5000) IROM(%s,%s) CLOCK(8000000) CPUTYPE("Cortex-M3") ELITTLE' % (irom_base, irom_size)),
     ('FlashUtilSpec',''),('StartupFile',''),('FlashDriverDll',''),('DeviceId','0'),
     ('RegisterFile',''),('OutputDirectory','..\\build\\keil\\'),('OutputName',output_name),
     ('CreateExecutable','1'),('CreateLib','0'),('CreateHexFile','1'),('DebugInformation','1'),
     ('BrowseInformation','0'),('ListingPath','..\\build\\keil\\'),('HexFormatSelection','1')]:sub(common,k,v)
    # Optional BIN export: user selects fromelf path for installed compiler; disabled by default.
    after=sub(common,'AfterMake')
    for k,v in [('RunUserProg1','0'),('RunUserProg2','0'),('UserProg1Name','"$KARM\\ARMCLANG\\bin\\fromelf.exe" --bin --output "..\\build\\keil\\%s.bin" "..\\build\\keil\\%s.axf"' % (output_name, output_name)),('UserProg2Name',''),('UserProg1Dos16Mode','0'),('UserProg2Dos16Mode','0'),('nStopA1X','1'),('nStopA2X','0')]:sub(after,k,v)
    arm=sub(opt,'TargetArmAds'); misc=sub(arm,'ArmAdsMisc')
    for k,v in [('GenerateListings','0'),('asHll','1'),('asAsm','1'),('asMacX','1'),('asSyms','1'),('asFals','1'),('asDbgD','1'),('asForm','1'),('ldLst','1'),('ldmm','1'),('ldXref','1'),('BigEnd','0'),('AdsALst','0'),('AdsACrf','0'),('AdsANop','0'),('AdsANot','0'),('AdsLLst','1'),('AdsLmap','1'),('AdsLcgr','1'),('AdsLsym','1'),('AdsLszi','1'),('AdsLtoi','1'),('AdsLsun','1'),('AdsLven','1'),('AdsLsxf','1'),('RvctClst','0'),('GenPPlst','0'),('AdsCpuType','"Cortex-M3"'),('RvctDeviceName',''),('mOS','0'),('uocRom','0'),('uocRam','0'),('hadIROM','1'),('hadIRAM','1'),('hadXRAM','0'),('uocXRam','0'),('RvdsVP','0'),('hadIRAM2','0'),('hadIROM2','0'),('StupSel','8'),('useUlib','0')]:sub(misc,k,v)
    cads=sub(arm,'Cads')
    for k,v in [('interw','1'),('Optim',optim),('oTime','0'),('SplitLS','0'),('OneElfS','1'),('Strict','0'),('EnumInt','0'),('PlainCh','0'),('Ropi','0'),('Rwpi','0'),('wLevel','2'),('uThumb','0'),('uSurpInc','0'),('uC99','1'),('v6Lang','1'),('v6LangP','1'),('vShortEn','0'),('vShortWch','0')]:sub(cads,k,v)
    controls=sub(cads,'VariousControls')
    sub(controls,'MiscControls','-std=c11 -Wall -Wextra -Werror -ffunction-sections -fdata-sections')
    sub(controls,'Define','STM32F10X_MD');sub(controls,'Undefine','')
    sub(controls,'IncludePath',';'.join('..' if s=='.' else '..\\'+s.replace('/','\\') for s in includes))
    ld=sub(arm,'LDads')
    for k,v in [('umfTarg','0'),('Ropi','0'),('Rwpi','0'),('noStLib','0'),('RepFail','1'),('useFile','1'),('TextAddressRange',irom_base),('DataAddressRange','0x20000000'),('pXoBase',''),('ScatterFile','.\\'+scatter),('IncludeLibs',''),('IncludeLibsPath',''),('Misc','--entry=Reset_Handler --strict'),('LinkerInputFile',''),('DisabledWarnings','')]:sub(ld,k,v)
    group_nodes=sub(target,'Groups')
    for name,paths in groups.items():
        group=sub(group_nodes,'Group');sub(group,'GroupName',name);files=sub(group,'Files')
        for path in paths:
            f=sub(files,'File');sub(f,'FileName',Path(path).name);sub(f,'FileType','1');sub(f,'FilePath','..\\'+path.replace('/','\\'))
    ET.indent(project,space='  ')
    return '<?xml version="1.0" encoding="UTF-8" standalone="no" ?>\n'+ET.tostring(project,encoding='unicode',xml_declaration=False)+'\n'

app_includes=['.','bsp','hal/inc','app/inc','common/ota_frame','middlewares/FreeRTOS-Kernel/include','middlewares/FreeRTOS-Kernel/portable/GCC/ARM_CM3']
boot_includes=['bootloader/inc','bsp','common/ota_frame']
outputs={
 'tools/sources.mk':mk,
 'keil/MCU_Project.uvprojx':project('STM32F103C8_App',app_groups,'0x08002000','0xDC00','STM32F103C8.sct','firmware',app_includes,'2'),
 'keil/Bootloader.uvprojx':project('STM32F103C8_Bootloader',boot_groups,'0x08000000','0x2000','Bootloader.sct','bootloader',boot_includes,'2'),
}
check=argparse.ArgumentParser();check.add_argument('--check',action='store_true');args=check.parse_args()
for path,content in outputs.items():
    dest=root/path
    if args.check:
        if not dest.exists() or dest.read_text()!=content:raise SystemExit('Out of sync: '+path)
    else:
        dest.parent.mkdir(parents=True,exist_ok=True);dest.write_text(content, newline="\n")
print('Make/Keil source lists: OK (app %d, bootloader %d C files)' % (len(app_sources), len(boot_sources)))
